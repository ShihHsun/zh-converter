// 修正 opencc-js 字典轉錯的已知情況，詳見 docs/known-limitations.md
// 規則套用在 opencc 轉換「之後」：左邊是轉換後的錯誤寫法，右邊是修正後的寫法
// 比對時「越長的規則越優先」，所以左右相同的規則可以用來保護不該被改的詞
//
// 注意：新增規則前，先想想這個寫法會不會出現在其他正確的詞裡。
// 例如曾嘗試用「於小姐 → 于小姐」修正姓氏，結果把「屬於小姐」「由於先生」也改錯了，
// 所以姓氏問題沒有用規則處理，列在 docs/known-limitations.md。
const CUSTOM_RULES = {
  'cn-to-tw': [
    // 一字多義
    ['幹你什麼事', '干你什麼事'],

    // 兩岸同詞不同義：大陸的土豆是馬鈴薯
    ['土豆', '馬鈴薯'],
  ],
  'tw-to-cn': [
    // 反向用語：預設 → 默认
    ['预设', '默认'],
    // 保護：「预设立场」是正確用法
    ['预设立场', '预设立场'],
  ],
};

module.exports = { CUSTOM_RULES };